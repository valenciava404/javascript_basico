// ===========================
// EJERCICIO 1 = AREA DE UN TRIANGULO
// Formula: AT = (B * H) /2
// AT = Area del Triangulo
// B = Base
// H = Altura
// ============================

// Cambiar estos valores para probar el programa con otros datos.

const base = 10; // Base del triangulo (numero)
const altura = 4; // Altura del triangulo (numero)

// Aplicamos la formula del area; (base por altura dividido entre 2)
const areaTriangulo = (base * altura) / 2;

// Mostrar en consola los datos de entrada junto al resultado obtenido.
console.log("==== AREA DE UN TRINGULO");
console.log("La base es; ", base); // Imprime el valor de la base.
console.log("La altura es; ", altura); // Imprime el valor de la altura.
console.log("El area del triangulo es; ", areaTriangulo); // Imprime el resultado final